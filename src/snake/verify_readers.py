"""Check that pyreadstat and DuckDB return the same data, chunk by chunk.

Both readers are asked for the same row window (offset/limit) of
data/cbs/file.<format>, and the resulting polars dataframes are compared with
`polars.testing.assert_frame_equal`. Use --chunks to control how many chunks are
compared.

The cbs files are generated by src/snake/create_stat_file.py with no missing
values and no user-missing ranges, so every difference reported here is a real
one: both tools should return identical data.

Usage:
    uv run src/snake/verify_readers.py dta --chunks 3 --chunksize 100000
    uv run src/snake/verify_readers.py sav --chunks 1
"""

# /// script
# dependencies = [
#   "pyreadstat",
#   "polars",
#   "duckdb<2.0.0",
#   "pyarrow",
# ]
# ///

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import polars as pl
from polars.testing import assert_frame_equal

from readers import (
    DEFAULT_CHUNKSIZE,
    FORMATS,
    get_con,
    number_of_rows,
    pyreadstat_reader,
    read_stat_call,
    resolve_in_file,
)


def read_chunk_pyreadstat(
    in_file: str | Path, file_format: str, offset: int, limit: int
) -> pl.DataFrame:
    """Rows [offset, offset + limit) as read by pyreadstat."""
    data, _meta = pyreadstat_reader(file_format)(
        str(in_file),
        row_offset=offset,
        row_limit=limit,
        output_format="polars",
    )
    return data


def read_chunk_duckdb(
    con, in_file: str | Path, file_format: str, offset: int, limit: int
) -> pl.DataFrame:
    """Rows [offset, offset + limit) as read by DuckDB."""
    query = (
        f"SELECT * FROM {read_stat_call(in_file, file_format)} "
        f"LIMIT {limit} OFFSET {offset}"
    )
    return con.sql(query).pl()


def compare_chunk(py: pl.DataFrame, duck: pl.DataFrame) -> str | None:
    """Call polars.testing.assert_frame_equal; return its message if they differ."""
    try:
        # check_dtypes=False: compare values, not the int/float type each
        # reader happens to produce.
        assert_frame_equal(py, duck, check_dtypes=False)
    except AssertionError as exc:
        return str(exc)
    return None


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "format", nargs="?", default="sav", choices=FORMATS, help="file format"
    )
    parser.add_argument(
        "--chunks", type=int, default=1, help="how many chunks to compare (default: 1)"
    )
    parser.add_argument(
        "--chunksize",
        type=int,
        default=DEFAULT_CHUNKSIZE,
        help="rows per chunk (default: %(default)s)",
    )
    args = parser.parse_args()
    if args.chunks < 1:
        raise SystemExit("--chunks must be >= 1")
    if args.chunksize < 1:
        raise SystemExit("--chunksize must be >= 1")

    in_file = resolve_in_file(args.format)
    n_rows = number_of_rows(in_file, args.format)
    print(
        f"comparing {args.chunks} chunk(s) of {args.chunksize} rows "
        f"from {in_file} ({n_rows} rows)"
    )
    con = get_con()

    n_problems = 0
    for chunk in range(args.chunks):
        offset = chunk * args.chunksize
        if offset >= n_rows:
            print(f"chunk {chunk}: past the end of the file, stopping")
            break
        limit = min(args.chunksize, n_rows - offset)
        py = read_chunk_pyreadstat(in_file, args.format, offset, limit)
        duck = read_chunk_duckdb(con, in_file, args.format, offset, limit)
        problem = compare_chunk(py, duck)
        status = "OK" if problem is None else "MISMATCH"
        print(
            f"chunk {chunk} (rows {offset:,}..{offset + limit - 1:,}): "
            f"pyreadstat={py.height} rows, duckdb={duck.height} rows, {status}"
        )
        if problem is not None:
            print("\n".join(f"  {line}" for line in problem.splitlines()))
            n_problems += 1

    if n_problems:
        print(f"\n{n_problems} chunk(s) differ")
        sys.exit(1)
    print("\nall compared chunks match")


if __name__ == "__main__":
    main()
